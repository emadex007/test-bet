"""Writes packs/<id>/seed.sql for every pack except interior.

Only needed when you change the sample content below. The interior pack's seed was written by hand.
Run from the project folder:  python scripts/build-seeds.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def U(pid: str, w: int = 1600) -> str:
    return f"https://images.unsplash.com/photo-{pid}?auto=format&fit=crop&w={w}&q=80"


def q(v) -> str:
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def header(name: str) -> str:
    return (
        f"-- SAMPLE content for the {name} pack, so the site isn't empty on day one.\n"
        "-- `npm run new-client` copies this file to migrations/0100_sample_content.sql.\n"
        "-- Photos are from Unsplash. Replace everything with the client's real content from the dashboard.\n"
        "-- Sample testimonials are switched OFF and labelled, so they never show as real reviews.\n"
        "-- Generated by scripts/build-seeds.py: edit that file, not this one.\n\n"
    )


def services_sql(services) -> str:
    out = []
    for i, (slug, title, summary, desc, image) in enumerate(services):
        out.append(
            "INSERT INTO services (slug,title,summary,description,image,sort_order) VALUES "
            f"({q(slug)},{q(title)},{q(summary)},{q(desc)},{q(U(image))},{i});"
        )
    return "\n".join(out) + "\n"


PROJECT_COLS = [
    "slug", "title", "category", "location", "year", "duration", "scope", "summary", "description", "cover_image",
    "featured", "sort_order", "listing_type", "price", "price_note", "bedrooms", "bathrooms", "area", "status", "amenities",
]


def projects_sql(projects) -> str:
    out = []
    for i, p in enumerate(projects):
        row = {c: "" for c in PROJECT_COLS}
        row.update({"featured": 0, "price": 0, "bedrooms": 0, "bathrooms": 0, "sort_order": i})
        row.update({k: v for k, v in p.items() if k != "photos"})
        row["cover_image"] = U(p["photos"][0][0])
        if isinstance(row["amenities"], list):
            row["amenities"] = "\n".join(row["amenities"])
        out.append(f"INSERT INTO projects ({','.join(PROJECT_COLS)}) VALUES ({','.join(q(row[c]) for c in PROJECT_COLS)});")
        for j, (pid, caption) in enumerate(p["photos"]):
            out.append(
                "INSERT INTO project_photos (project_id,url,caption,sort_order) VALUES "
                f"((SELECT id FROM projects WHERE slug = {q(p['slug'])}),{q(U(pid))},{q(caption)},{j});"
            )
        out.append("")
    return "\n".join(out)


def testimonials_sql(samples) -> str:
    rows = [
        f"  ('SAMPLE: replace with client name', {q(role)}, {q(text)}, {100 + i}, 0)"
        for i, (role, text) in enumerate(samples)
    ]
    return "INSERT INTO testimonials (name, role, quote, sort_order, active) VALUES\n" + ",\n".join(rows) + ";\n"


def faqs_sql(faqs) -> str:
    rows = [f"  ({q(a)}, {q(b)}, {i})" for i, (a, b) in enumerate(faqs)]
    return "INSERT INTO faqs (question, answer, sort_order) VALUES\n" + ",\n".join(rows) + ";\n"


